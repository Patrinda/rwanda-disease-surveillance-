def pick_age(group, rng):
    if group == "u5":
        return rng.randint(0, 4)
    if group == "child":
        return rng.randint(1, 14)
    if group == "adult":
        return rng.randint(18, 64)
    lo, hi = rng.choices([(0, 4), (5, 14), (15, 24), (25, 44), (45, 64), (65, 85)], weights=[15, 20, 18, 27, 14, 6])[0]
    return rng.randint(lo, hi)


def season_weight(category, month):
    if category in (C.VECTOR, C.WATER_FOOD):
        return 1 + 0.35 * math.cos(2 * math.pi * (month - 4) / 6)      # two rainy seasons
    if category == C.RESPIRATORY:
        return 1 + 0.2 * math.cos(2 * math.pi * (month - 8) / 12)
    return 1.0


class Command(BaseCommand):
    help = "Create fictional demonstration data (provinces and districts are created by the migrations)."

    def add_arguments(self, parser):
        parser.add_argument("--reset", action="store_true", help="Delete patients, reports and outbreaks first.")

    @transaction.atomic
    def handle(self, *args, **options):
        if options["reset"]:
            Outbreak.objects.all().delete()
            CaseReport.objects.all().delete()
            Patient.objects.all().delete()
            self.stdout.write("Old patients, reports and outbreaks removed.")
        elif CaseReport.objects.exists():
            self.stdout.write(self.style.WARNING("The database already has reports. Use --reset to rebuild the demo data."))
            return

        rng = random.Random(2026)
        today = timezone.localdate()

        ensure_groups()
        users = self.create_users()
        diseases = self.create_diseases()
        districts = {d.name: d for d in District.objects.all()}
        if len(districts) != 30:
            self.stderr.write("Expected 30 districts. Run: python manage.py migrate")
            return

        owner_by_district = {"Gasabo": users["reporter_kigali"], "Huye": users["officer_huye"], "Kayonza": users["officer_kayonza"]}
        default_owner = users["admin"]

        patients, reports = [], []          # unsaved objects
        patient_pool = {}                   # district name -> list of unsaved patients
        active_pairs = set()                # (id(patient), disease code) already active

        def new_patient(district_name, age_group):
            sex = "F" if rng.random() < 0.52 else "M"
            name = f"{rng.choice(FEMALE if sex == 'F' else MALE)} {rng.choice(SURNAMES)}"
            phone = f"07{rng.choice('8923')}{rng.randint(0, 9999999):07d}" if rng.random() < 0.8 else ""
            p = Patient(patient_code=f"TMP-{uuid.uuid4().hex[:12]}", full_name=name, age=pick_age(age_group, rng),
                        gender=sex, phone=phone, district=districts[district_name])
            patients.append(p)
            patient_pool.setdefault(district_name, []).append(p)
            return p

        def add_report(code, district_name, days_ago, deceased_pct, age_group, force_new=False):
            disease = diseases[code]
            date_reported = today - timedelta(days=days_ago)
            pool = patient_pool.get(district_name, [])
            patient = None
            if pool and not force_new and rng.random() > 0.6:
                candidate = rng.choice(pool)
                if (id(candidate), code) not in active_pairs:
                    patient = candidate
            if patient is None:
                patient = new_patient(district_name, age_group)
            # outcome depends on how recent the report is
            roll = rng.random() * 100
            if roll < deceased_pct:
                status = "deceased"
            elif days_ago < 14:
                status = "active" if rng.random() < 0.8 else "recovered"
            elif days_ago < 35:
                status = "active" if rng.random() < 0.3 else "recovered"
            else:
                status = "active" if rng.random() < 0.04 else "recovered"
            if status == "active":
                if (id(patient), code) in active_pairs:
                    status = "recovered"
                else:
                    active_pairs.add((id(patient), code))
            suspected_share = 0.85 if code in ("VHF", "MR", "AFP") else (0.35 if code == "COV" else 0.55)
            report = CaseReport(
                patient=patient, disease=disease, district=districts[district_name],
                case_type="suspected" if rng.random() < suspected_share else "confirmed",
                status=status, date_reported=date_reported,
                date_onset=date_reported - timedelta(days=rng.randint(0, 6)),
                reported_by=owner_by_district.get(district_name, default_owner),
            )
            reports.append(report)
            return report

        meta = {d[0]: d for d in DISEASES}
        planted_pairs = {(code, dist) for code, dist in PLANTED}

        # 1. Planted weekly counts that create the alerts and watches
        for (code, dist), buckets in PLANTED.items():
            for k, count in enumerate(buckets):
                for _ in range(count):
                    add_report(code, dist, rng.randint(7 * k, 7 * k + 6), meta[code][8], meta[code][7])

        # 2. Older Rift Valley fever reports (concentrated in Kayonza and Ngoma)
        for dist, count in RVF_OLDER.items():
            for _ in range(count):
                add_report("RVF", dist, rng.randint(35, 107), meta["RVF"][8], meta["RVF"][7])

        # 3. A past foodborne illness event in Gicumbi that was investigated and closed
        gicumbi_event = [add_report("FBI", "Gicumbi", rng.randint(196, 210), 0.0, "all") for _ in range(18)]

        # 4. Background reports for every other disease over the last 12 months
        district_names = list(districts)
        d_weights = [DISTRICT_WEIGHTS.get(n, 3) for n in district_names]
        window_counts = {}
        background = [d for d in DISEASES if d[6] > 0]
        total_weight = sum(d[6] for d in background)
        target = 1500
        for code, name, category, reporting, mult, minimum, weight, age_group, deaths, _ in background:
            count = round(target * weight / total_weight)
            day_weights = []
            for days_ago in range(365):
                month = (today - timedelta(days=days_ago)).month
                day_weights.append(season_weight(category, month) * (1 + 0.3 * (1 - days_ago / 365)))
            for _ in range(count):
                dist = rng.choices(district_names, weights=d_weights)[0]
                days_ago = rng.choices(range(365), weights=day_weights)[0]
                if (code, dist) in planted_pairs and days_ago < 35:
                    days_ago = rng.randint(35, 364)
                elif days_ago < 7:
                    used = window_counts.get((code, dist), 0)
                    if used >= minimum - 1:        # keep background noise below the alert threshold
                        days_ago = rng.randint(7, 364)
                    else:
                        window_counts[(code, dist)] = used + 1
                add_report(code, dist, days_ago, deaths, age_group)

        # 5. A few rare events well outside the last 5 weeks (the rare diseases have no recent reports)
        for code, dist, ago in [("VHF", "Rusizi", 150), ("VHF", "Nyagatare", 151), ("AFP", "Huye", 120), ("AFP", "Gakenke", 300),
                                ("CHO", "Rubavu", 200), ("CHO", "Rubavu", 201), ("CHO", "Rusizi", 203), ("MPX", "Kicukiro", 90),
                                ("MPX", "Gasabo", 95), ("MPX", "Gasabo", 99), ("TRY", "Nyagatare", 250)]:
            add_report(code, dist, ago, meta[code][8], meta[code][7])

        # Save everything
        Patient.objects.bulk_create(patients)
        for p in patients:
            p.patient_code = f"P-{p.pk:05d}"
        Patient.objects.bulk_update(patients, ["patient_code"], batch_size=500)
        for r in reports:
            r.patient_id = r.patient.pk
            r.disease_id = r.disease.pk
            r.district_id = r.district.pk
        CaseReport.objects.bulk_create(reports, batch_size=500)

        # Outbreak records
        admin = users["admin"]
        rvf_kayonza = Outbreak.objects.create(
            disease=diseases["RVF"], district=districts["Kayonza"], level="alert", status="open",
            start_date=today - timedelta(days=60), auto_detected=True, declared_by=admin,
            notes="Rift Valley fever in livestock and people around Kayonza. Quarantine, vaccination and community follow-up are ongoing.",
        )
        rvf_kayonza.cases.set(CaseReport.objects.filter(disease=diseases["RVF"], district=districts["Kayonza"]))
        closed = Outbreak.objects.create(
            disease=diseases["FBI"], district=districts["Gicumbi"], level="alert", status="closed",
            start_date=today - timedelta(days=210), end_date=today - timedelta(days=190), auto_detected=False,
            declared_by=admin, notes="Illness after a social gathering. Source found and the event was closed after 20 days.",
        )
        closed.cases.set(CaseReport.objects.filter(disease=diseases["FBI"], district=districts["Gicumbi"],
                                                   date_reported__lte=today - timedelta(days=190)))

        alerts = current_alerts()
        self.stdout.write(self.style.SUCCESS(
            f"Created {Patient.objects.count()} patients, {CaseReport.objects.count()} case reports, "
            f"{Outbreak.objects.count()} outbreak records and {Disease.objects.count()} diseases."))
        self.stdout.write("Current alerts and watches:")
        for a in alerts:
            self.stdout.write(f"  {a['level'].upper():5s}  {a['disease'].name} in {a['district'].name}: {a['current']} this week, usual {a['baseline']}")
        self.stdout.write("\nDemo accounts:")
        for username, password in DEMO_PASSWORDS.items():
            self.stdout.write(f"  {username:16s} password: {password}")

    def create_users(self):
        User = get_user_model()
        spec = [
            ("admin", "System", "Administrator", True, ROLE_ADMIN, None, "National Epidemiologist"),
            ("officer_kayonza", "Kayonza", "Officer", False, ROLE_OFFICER, "Kayonza", "District Health Officer"),
            ("officer_huye", "Huye", "Officer", False, ROLE_OFFICER, "Huye", "District Health Officer"),
            ("reporter_kigali", "Gasabo", "Reporter", False, ROLE_REPORTER, "Gasabo", "Health Facility Data Manager"),
        ]
        users = {}
        for username, first, last, is_admin, role, district, title in spec:
            user, _ = User.objects.get_or_create(username=username)
            user.first_name, user.last_name = first, last
            user.email = f"{username}@example.com"
            user.is_staff = is_admin
            user.is_superuser = is_admin
            user.set_password(DEMO_PASSWORDS[username])
            user.save()
            user.groups.set([Group.objects.get(name=role)])
            profile = user.profile
            profile.district = District.objects.filter(name=district).first() if district else None
            profile.job_title = title
            profile.save()
            users[username] = user
        return users

    def create_diseases(self):
        out = {}
        for code, name, category, reporting, mult, minimum, _w, _a, _d, description in DISEASES:
            disease, _ = Disease.objects.update_or_create(
                code=code,
                defaults=dict(name=name, category=category, reporting=reporting, alert_multiplier=mult,
                              min_cases_for_alert=minimum, description=description, is_active=True),
            )
            out[code] = disease
        return out
